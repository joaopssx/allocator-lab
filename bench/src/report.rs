//! Turns results into a Markdown file and two SVG charts.
//!
//! The SVG is written by hand. A plotting crate would pull in font handling
//! for two bar charts, and plain SVG renders fine on GitHub.

use crate::Cell;
use crate::scenarios;
use crate::switch::Kind;
use std::fmt::Write;

type Rows<'a> = [(&'a str, Vec<Cell>)];

const COLORS: [&str; 7] = [
    "#555555", "#d62728", "#1f77b4", "#6baed6", "#9ecae1", "#2ca02c", "#ff7f0e",
];

/// Peak memory used by the allocator over bytes requested, as a percentage
/// of waste: 0 means every byte taken served a request.
fn waste(c: &Cell) -> Option<f64> {
    match c {
        Cell::Done { peak: Some(u), .. } if u.used > 0 => {
            Some(100.0 * (1.0 - u.requested as f64 / u.used as f64))
        }
        _ => None,
    }
}

/// Share of the free bytes not usable by a single request.
fn external(c: &Cell) -> Option<f64> {
    match c {
        Cell::Done { peak: Some(u), .. } if u.free > 0 => u
            .largest
            .map(|l| 100.0 * (1.0 - l.min(u.free) as f64 / u.free as f64)),
        _ => None,
    }
}

/// The full results file.
pub fn markdown(rows: &Rows) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "<!-- Generated by `cargo run --release -p bench -- --write`. Do not edit. -->\n"
    );
    let _ = writeln!(s, "# Benchmark results\n");
    let _ = writeln!(
        s,
        "Target: {}-{}. Each cell is the median of {} runs in a fresh process.\n",
        std::env::consts::ARCH,
        std::env::consts::OS,
        crate::RUNS
    );

    let _ = writeln!(s, "## Time per operation\n");
    let _ = writeln!(
        s,
        "Nanoseconds per operation (lower is better), with millions of operations per second in parentheses. An operation is one allocator call, except in `vec-growth` and `hashmap`, where it is one push or one insert or removal, most of which do not allocate. Lab allocators run with the `stats` feature on.\n"
    );
    header(&mut s);
    for (name, cells) in rows {
        let _ = write!(s, "| {name} |");
        for c in cells {
            let _ = match c {
                Cell::Done { ns, .. } => write!(s, " {ns:.1} ({:.0}) |", 1000.0 / ns),
                Cell::Failed(why) => write!(s, " {why} |"),
            };
        }
        let _ = writeln!(s);
    }

    let _ = writeln!(s, "\n## Memory at the peak\n");
    let _ = writeln!(
        s,
        "Internal: share of the memory taken from the allocator that no request asked for (headers, rounding, padding). External: share of the free memory that is not in the largest free block. The system allocator does not expose either.\n"
    );
    let _ = write!(s, "| scenario |");
    for k in &Kind::ALL[1..] {
        let _ = write!(s, " {} |", k.name());
    }
    let _ = write!(s, "\n|---|");
    for _ in &Kind::ALL[1..] {
        let _ = write!(s, "---|");
    }
    let _ = writeln!(s);
    for (name, cells) in rows {
        let _ = write!(s, "| {name} |");
        for c in &cells[1..] {
            let pct = |v: Option<f64>| v.map_or("-".to_string(), |x| format!("{x:.0}%"));
            let _ = match c {
                Cell::Failed(why) => write!(s, " {why} |"),
                _ => write!(s, " {} / {} |", pct(waste(c)), pct(external(c))),
            };
        }
        let _ = writeln!(s);
    }

    let _ = writeln!(s, "\n## Scenarios\n");
    for (name, what, _) in scenarios::ALL {
        let _ = writeln!(s, "- `{name}`: {what}.");
    }
    s
}

fn header(s: &mut String) {
    let _ = write!(s, "| scenario |");
    for k in Kind::ALL {
        let _ = write!(s, " {} |", k.name());
    }
    let _ = write!(s, "\n|---|");
    for _ in Kind::ALL {
        let _ = write!(s, "---|");
    }
    let _ = writeln!(s);
}

/// Grouped horizontal bars, one group per scenario, one bar per allocator.
/// `value` maps a cell to a bar length in `0.0..=1.0`, `label` to its text.
fn bars(
    title: &str,
    rows: &Rows,
    kinds: &[Kind],
    first: usize,
    value: impl Fn(&Cell) -> Option<f64>,
    label: impl Fn(&Cell) -> String,
    axis: &[(f64, String)],
) -> String {
    let (left, width, bar, gap) = (110.0, 520.0, 9.0, 14.0);
    let group = bar * kinds.len() as f64 + gap;
    let top = 40.0;
    let height = top + group * rows.len() as f64 + 60.0;
    let mut s = String::new();
    let _ = writeln!(
        s,
        r#"<svg xmlns="http://www.w3.org/2000/svg" width="720" height="{height}" font-family="sans-serif" font-size="10">"#
    );
    let _ = writeln!(s, r#"<rect width="100%" height="100%" fill="white"/>"#);
    let _ = writeln!(
        s,
        r#"<text x="{left}" y="20" font-size="13" font-weight="bold">{title}</text>"#
    );
    for (x, text) in axis {
        let px = left + x * width;
        let _ = writeln!(
            s,
            r##"<line x1="{px}" y1="{top}" x2="{px}" y2="{}" stroke="#ddd"/><text x="{px}" y="{}" text-anchor="middle">{text}</text>"##,
            height - 50.0,
            height - 38.0
        );
    }
    for (g, (name, cells)) in rows.iter().enumerate() {
        let y0 = top + g as f64 * group;
        let _ = writeln!(
            s,
            r#"<text x="{}" y="{}" text-anchor="end">{name}</text>"#,
            left - 6.0,
            y0 + bar * kinds.len() as f64 / 2.0 + 3.0
        );
        for (i, k) in kinds.iter().enumerate() {
            let c = &cells[first + i];
            let y = y0 + i as f64 * bar;
            match value(c) {
                Some(v) => {
                    let w = (v.clamp(0.0, 1.0) * width).max(1.0);
                    let _ = writeln!(
                        s,
                        r#"<rect x="{left}" y="{y}" width="{w:.1}" height="{}" fill="{}"/><text x="{:.1}" y="{}" font-size="8">{}</text>"#,
                        bar - 1.0,
                        COLORS[*k as usize],
                        left + w + 3.0,
                        y + bar - 2.0,
                        label(c)
                    );
                }
                None => {
                    let _ = writeln!(
                        s,
                        r##"<text x="{}" y="{}" font-size="8" fill="#999">{}</text>"##,
                        left + 3.0,
                        y + bar - 2.0,
                        label(c)
                    );
                }
            }
        }
    }
    let mut x = left;
    for k in kinds {
        let _ = writeln!(
            s,
            r#"<rect x="{x}" y="{}" width="10" height="10" fill="{}"/><text x="{}" y="{}">{}</text>"#,
            height - 22.0,
            COLORS[*k as usize],
            x + 14.0,
            height - 13.0,
            k.name()
        );
        x += 85.0;
    }
    let _ = writeln!(s, "</svg>");
    s
}

/// Time per operation relative to the system allocator, on a log scale
/// from 1/8x to 8x.
pub fn time_chart(rows: &Rows) -> String {
    let rel = |rows: &Rows, c: &Cell, g: usize| -> Option<f64> {
        let Cell::Done { ns: base, .. } = rows[g].1[0] else {
            return None;
        };
        match c {
            Cell::Done { ns, .. } => Some(ns / base),
            Cell::Failed(_) => None,
        }
    };
    // `bars` does not know the group of a cell, so precompute per row.
    let scaled: Vec<(&str, Vec<Cell>)> = rows
        .iter()
        .enumerate()
        .map(|(g, (name, cells))| {
            let cells = cells
                .iter()
                .map(|c| match rel(rows, c, g) {
                    Some(r) => Cell::Done { ns: r, peak: None },
                    None => c.clone(),
                })
                .collect();
            (*name, cells)
        })
        .collect();
    let pos = |r: f64| (r.log2() + 3.0) / 6.0;
    let axis: Vec<(f64, String)> = [0.125, 0.25, 0.5, 1.0, 2.0, 4.0, 8.0]
        .iter()
        .map(|&r| (pos(r), format!("{r}x")))
        .collect();
    bars(
        "Time per operation relative to the system allocator (log scale, shorter is faster)",
        &scaled,
        &Kind::ALL,
        0,
        |c| match c {
            Cell::Done { ns, .. } => Some(pos(*ns)),
            Cell::Failed(_) => None,
        },
        |c| match c {
            Cell::Done { ns, .. } => format!("{ns:.2}x"),
            Cell::Failed(why) => why.to_string(),
        },
        &axis,
    )
}

/// Internal fragmentation at the peak, per lab allocator.
pub fn overhead_chart(rows: &Rows) -> String {
    let axis: Vec<(f64, String)> = (0..=4)
        .map(|i| (i as f64 / 4.0, format!("{}%", i * 25)))
        .collect();
    bars(
        "Memory taken but not requested, at the peak (internal fragmentation)",
        rows,
        &Kind::ALL[1..],
        1,
        |c| waste(c).map(|w| w / 100.0),
        |c| match (c, waste(c)) {
            (_, Some(w)) => format!("{w:.0}%"),
            (Cell::Failed(why), _) => why.to_string(),
            _ => "-".to_string(),
        },
        &axis,
    )
}
